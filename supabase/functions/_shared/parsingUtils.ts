/**
 * Data Filtration Utility for Supabase Edge Runtime
 * Clean AI Responses for Contract Processing
 *
 * This utility provides robust functions to parse AI conversational responses
 * and extract only the legal text of contracts, optimized for Deno runtime.
 */

export interface ContractParsingOptions {
  preserveFormatting?: boolean;
  removeHeaders?: boolean;
  removeFooters?: boolean;
}

/**
 * Clean contract text by removing conversational artifacts and formatting
 *
 * CRITICAL: This function acts as the "filtration" step in our data pipeline.
 * It removes conversational filler, markdown formatting, and AI artifacts
 * BEFORE the data reaches the PDF generation service.
 */
export function cleanContractText(rawAiResponse: string, options: ContractParsingOptions = {}): string {
  let cleanedText = rawAiResponse;

  // 1. Remove conversational intro phrases (comprehensive list)
  const introPatterns = [
    /Here is the upgraded contract incorporating the requested changes\./gi,
    /Here is the upgraded contract.*for your review\./gi,
    /Here is the revised contract as requested:/gi,
    /Here is your upgraded contract:/gi,
    /Below is the revised contract:/gi,
    /I've created the following contract for you:/gi,
    /Here's the contract draft:/gi,
    /The upgraded contract is as follows:/gi,
    /Here is the complete upgraded contract:/gi,
    /Here's the upgraded version:/gi,
    /Here is the contract:/gi,
    /The contract is as follows:/gi,
    /Below is the contract:/gi,
    /Here's your contract:/gi,
    /I have created the following contract:/gi,
    /The revised contract is:/gi,
    /Here is the revised version:/gi,
    /Here is the final contract:/gi,
    /Here's what I came up with:/gi,
    /Based on your requirements, here is the contract:/gi,
    /Here is the upgraded.*changes.*marked/gi,
    /The additions are clearly marked/gi,
    /Changes are clearly marked with comments/gi,
  ];

  introPatterns.forEach(pattern => {
    cleanedText = cleanedText.replace(pattern, '');
  });

  // 2. Remove "Summary of Changes" and everything after it
  cleanedText = cleanedText.split(/\*\*Summary of Changes:\*\*/)[0];
  cleanedText = cleanedText.split(/Summary of Changes:/)[0];
  cleanedText = cleanedText.split(/\*\*Changes Made:\*\*/)[0];
  cleanedText = cleanedText.split(/Changes Made:/)[0];
  cleanedText = cleanedText.split(/\*\*Summary:\*\*/)[0];
  cleanedText = cleanedText.split(/Summary:/)[0];

  // 3. Remove Markdown code fences (```text, ```json, ```, etc.)
  cleanedText = cleanedText.replace(/```[a-z]*\n?/gi, ''); // Remove opening fences with language
  cleanedText = cleanedText.replace(/```\n?/g, ''); // Remove plain fences

  // 4. Remove specific problematic code block patterns
  cleanedText = cleanedText.replace(/```text\s+UPGRADED\s+CONTRACT/gi, '');
  cleanedText = cleanedText.replace(/```UPGRADED\s+CONTRACT/gi, '');
  cleanedText = cleanedText.replace(/```text/gi, '');

  // 5. Remove markdown headers that aren't part of the contract
  if (options.removeHeaders !== false) {
    const headerPatterns = [
      /^#+\s*Contract\s+Analysis.*$/gm,
      /^#+\s*Analysis\s+Report.*$/gm,
      /^#+\s*Document\s+Summary.*$/gm,
      /^#+\s*Key\s+Changes.*$/gm,
      /^#+\s*Summary.*$/gm,
      /^#+\s*Contract.*$/gm,
      /^#+\s*Agreement.*$/gm,
    ];

    headerPatterns.forEach(pattern => {
      cleanedText = cleanedText.replace(pattern, '');
    });
  }

  // 6. Remove common AI-generated metadata and artifacts
  const metadataPatterns = [
    /\*\*Generated by.*?\*\*/gi,
    /\*Generated by.*?\*/gi,
    /Generated by.*/gi,
    /\*\*Created on.*?\*\*/gi,
    /\*\*Last modified.*?\*\*/gi,
    /---[\s\S]*?---/g, // Remove markdown separators
    /\[.*?\]/g, // Remove bracketed metadata
    /^\s*\[.*?\]\s*$/gm, // Remove lines that are just bracketed content
    /\*\*Changes are marked with.*?\*\*/gi,
    /\*Changes are marked with.*?\*/gi,
    /Changes are marked with.*/gi,
  ];

  metadataPatterns.forEach(pattern => {
    cleanedText = cleanedText.replace(pattern, '');
  });

  // 7. Clean up excessive whitespace and empty lines
  cleanedText = cleanedText.replace(/\n\s*\n\s*\n/g, '\n\n'); // Remove excessive consecutive empty lines
  cleanedText = cleanedText.replace(/^\s*\n+/gm, ''); // Remove leading empty lines
  cleanedText = cleanedText.replace(/\s*\n\s*$/gm, ''); // Remove trailing empty lines

  // 8. Find the actual contract start (aggressive cleaning for stubborn cases)
  const contractStartPatterns = [
    /^This Agreement/im,
    /^This Contract/im,
    /^WHEREAS/im,
    /^BETWEEN/im,
    /^PARTIES:/im,
    /^AGREEMENT/im,
    /^CONTRACT/im,
    /^The Parties:/im,
    /^1\./im, // Numbered clauses
    /^I\./im, // Roman numerals
    /^A\./im, // Lettered clauses
    /^Section\s+\d+/im,
    /^Article\s+\d+/im,
    /^#+\s*(Parties|Definitions|Term|Payment|Signatures?|Scope|Obligations)/im,
  ];

  for (const pattern of contractStartPatterns) {
    const match = cleanedText.match(pattern);
    if (match && match.index && match.index > 10) {
      // Only cut if we're removing a significant amount of unwanted text
      if (match.index > 30) {
        cleanedText = cleanedText.substring(match.index);
        break;
      }
    }
  }

  // 9. Final cleanup
  cleanedText = cleanedText.trim();

  return cleanedText;
}

/**
 * Validate contract text quality
 */
export function validateContractText(contractText: string): {
  isValid: boolean;
  issues: string[];
  score: number;
} {
  const issues: string[] = [];
  let score = 100;

  // Check for minimum length
  if (contractText.length < 100) {
    issues.push('Contract text is too short');
    score -= 30;
  }

  // Check for common contract keywords
  const contractKeywords = ['agreement', 'contract', 'party', 'parties', 'whereas', 'therefore'];
  const foundKeywords = contractKeywords.filter(keyword =>
    contractText.toLowerCase().includes(keyword)
  );

  if (foundKeywords.length < 3) {
    issues.push('Missing common contract keywords');
    score -= 20;
  }

  // Check for excessive markdown or formatting artifacts
  const artifactCount = (contractText.match(/[#*_`]/g) || []).length;
  if (artifactCount > contractText.length * 0.1) {
    issues.push('Excessive formatting artifacts detected');
    score -= 15;
  }

  // Check for conversational language
  const conversationalWords = ['here is', 'below is', 'i have', 'created', 'generated'];
  const hasConversational = conversationalWords.some(word =>
    contractText.toLowerCase().includes(word)
  );

  if (hasConversational) {
    issues.push('Conversational language detected');
    score -= 25;
  }

  return {
    isValid: issues.length === 0,
    issues,
    score: Math.max(0, score)
  };
}

/**
 * Advanced contract text cleaning with quality validation
 */
export function cleanAndValidateContractText(rawAiResponse: string, options: ContractParsingOptions = {}): {
  contractText: string;
  validation: {
    isValid: boolean;
    issues: string[];
    score: number;
  };
} {
  const contractText = cleanContractText(rawAiResponse, options);
  const validation = validateContractText(contractText);

  return {
    contractText,
    validation
  };
}
