import { PDFDocument, rgb, StandardFonts, PDFFont } from 'pdf-lib';

interface ContractData {
    contract_title?: string;
    contract_subtitle?: string;
    contract_body: string;
    revision_number?: number;
    client_name?: string;
    generation_date?: string;
    logo_url?: string;
}

export class PDFGenerationService {
    constructor() {
        // No initialization needed for pdf-lib
    }

    /**
     * Generate a professional PDF document from contract data
     */
    public async generateContractPDF(contractData: ContractData): Promise<Buffer> {
        try {
            // --- START OF CRITICAL DIAGNOSTIC LOG ---
            console.log("--- PDFGEN SERVICE INPUT ---");
            console.log("Contract Body Length:", contractData.contract_body?.length || 0);
            console.log("Contract Body Preview (first 500 chars):");
            console.log(contractData.contract_body?.substring(0, 500) || "EMPTY");
            console.log("--------------------------");
            // --- END OF CRITICAL DIAGNOSTIC LOG ---

            const { contract_body, contract_title = 'Contract Document', revision_number = 1, generation_date } = contractData;

            // 1. Clean the contract text to remove unwanted content
            const cleanedText = this.cleanContractText(contract_body);

            // 2. Create a new PDF document in memory
            const pdfDoc = await PDFDocument.create();
            let page = pdfDoc.addPage();
            const { width, height } = page.getSize();

            // 3. Set up fonts and formatting
            const helveticaFont = await pdfDoc.embedFont(StandardFonts.Helvetica);
            const helveticaBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
            const fontSize = 12;
            const titleSize = 18;
            const margin = 50;
            let yPosition = height - margin;

            // 4. Add header/title
            page.drawText(contract_title.toUpperCase(), {
                x: margin,
                y: yPosition,
                font: helveticaBold,
                size: titleSize,
                color: rgb(0, 0, 0),
            });

            yPosition -= titleSize + 20;

            // Add revision and date if provided
            if (revision_number > 1) {
                page.drawText(`Revision ${revision_number}`, {
                    x: margin,
                    y: yPosition,
                    font: helveticaFont,
                    size: fontSize - 2,
                    color: rgb(0.4, 0.4, 0.4),
                });
                yPosition -= fontSize;
            }

            if (generation_date) {
                page.drawText(`Generated: ${generation_date}`, {
                    x: width - margin - 100,
                    y: yPosition,
                    font: helveticaFont,
                    size: fontSize - 2,
                    color: rgb(0.4, 0.4, 0.4),
                });
                yPosition -= fontSize + 10;
            }

            // 5. Add contract content with proper text wrapping
            const lines = this.wrapText(cleanedText, helveticaFont, fontSize, width - 2 * margin);
            const lineHeight = fontSize + 4;

            for (const line of lines) {
                if (yPosition < margin + lineHeight) {
                    // Add new page if needed
                    page = pdfDoc.addPage();
                    yPosition = height - margin;
                }

                page.drawText(line, {
                    x: margin,
                    y: yPosition,
                    font: helveticaFont,
                    size: fontSize,
                    color: rgb(0, 0, 0),
                });

                yPosition -= lineHeight;
            }

            // 6. Add footer
            const footerY = margin / 2;
            page.drawText('Generated by EZ Biz Contract', {
                x: margin,
                y: footerY,
                font: helveticaFont,
                size: fontSize - 2,
                color: rgb(0.6, 0.6, 0.6),
            });

            // 7. Serialize the PDFDocument to bytes (a Uint8Array)
            const pdfBytes = await pdfDoc.save();

            // 8. Return the raw PDF data as a Buffer
            return Buffer.from(pdfBytes);

        } catch (error) {
            console.error('❌ PDF generation error:', error);
            throw new Error(`Failed to generate PDF: ${error.message}`);
        }
    }

    /**
     * Wrap text to fit within specified width
     */
    private wrapText(text: string, font: PDFFont, fontSize: number, maxWidth: number): string[] {
        const words = text.split(' ');
        const lines: string[] = [];
        let currentLine = '';

        for (const word of words) {
            const testLine = currentLine ? `${currentLine} ${word}` : word;
            const textWidth = font.widthOfTextAtSize(testLine, fontSize);

            if (textWidth <= maxWidth) {
                currentLine = testLine;
            } else {
                if (currentLine) {
                    lines.push(currentLine);
                }
                currentLine = word;
            }
        }

        if (currentLine) {
            lines.push(currentLine);
        }

        return lines;
    }

    /**
     * Clean contract text by removing unwanted introduction and metadata
     */
    private cleanContractText(text: string): string {
        let cleaned = text;

        // Remove common unwanted introduction text patterns (comprehensive list)
        const unwantedPatterns = [
            // Main problematic patterns from user feedback
            /Here is the upgraded contract incorporating the requested changes\./gi,
            /The additions are clearly marked\./gi,
            /Changes are clearly marked with comments indicating the additions\./gi,
            /Here is your upgraded contract:/gi,
            /Below is the revised contract:/gi,
            /I've created the following contract for you:/gi,
            /Here's the contract draft:/gi,
            /The upgraded contract is as follows:/gi,
            /Here is the complete upgraded contract:/gi,
            /Here's the upgraded version:/gi,

            // Additional AI response patterns
            /Here is the contract:/gi,
            /The contract is as follows:/gi,
            /Below is the contract:/gi,
            /Here's your contract:/gi,
            /I have created the following contract:/gi,
            /The revised contract is:/gi,
            /Here is the revised version:/gi,

            // Markdown and formatting artifacts
            /\*\*Changes are marked with \[.*?\]\*\*/gi,
            /---[\s\S]*?---/g, // Remove markdown separators
            /```[\s\S]*?```/g, // Remove code blocks
            /`[\s\S]*?`/g, // Remove inline code
            /\[.*?\]/g, // Remove bracketed comments
            /^\s*\[.*?\]\s*$/gm, // Remove lines that are just bracketed comments

            // Headers that should be removed
            /^#+\s*(Contract|Agreement|Draft|Upgrade|Revised|Updated)/gim,

            // Common AI fluff
            /^Here is/gim,
            /^Below is/gim,
            /^The following/gim,
            /^I've prepared/gim,
            /^This is the/gim,
            /^As requested/gim,
            /^The upgraded contract:/gim,
            /^Upgraded Contract:/gim,
            /^Revised Contract:/gim,
            /^New Contract Version:/gim,
        ];

        // Apply all cleaning patterns
        unwantedPatterns.forEach(pattern => {
            cleaned = cleaned.replace(pattern, '');
        });

        // Remove excessive whitespace and empty lines at the beginning
        cleaned = cleaned.replace(/^\s*\n+/gm, '');
        cleaned = cleaned.replace(/\n\s*\n\s*\n/g, '\n\n'); // Remove excessive consecutive empty lines
        cleaned = cleaned.trim();

        // More aggressive cleaning: if text starts with common unwanted phrases, find contract start
        const aggressiveStartPatterns = [
            // Contract start patterns
            /^This Agreement/im,
            /^This Contract/im,
            /^WHEREAS/im,
            /^BETWEEN/im,
            /^PARTIES:/im,
            /^AGREEMENT/im,
            /^CONTRACT/im,
            /^The Parties:/im,
            /^1\./im, // Numbered clauses
            /^I\./im, // Roman numerals
            /^A\./im, // Lettered clauses
            /^Section\s+\d+/im,
            /^Article\s+\d+/im,

            // Header patterns that indicate actual contract content
            /^#+\s*(Parties|Definitions|Term|Payment|Signatures?|Scope|Obligations)/im,
        ];

        for (const pattern of aggressiveStartPatterns) {
            const match = cleaned.match(pattern);
            if (match && match.index > 0) {
                // Only cut if we're removing a significant amount of unwanted text
                if (match.index > 10) {
                    cleaned = cleaned.substring(match.index);
                    break;
                }
            }
        }

        // Final cleanup
        cleaned = cleaned.replace(/^\s*\n+/gm, ''); // Remove leading empty lines
        cleaned = cleaned.replace(/\n\s*\n\s*\n/g, '\n\n'); // Normalize multiple empty lines
        cleaned = cleaned.trim();

        return cleaned;
    }
}
