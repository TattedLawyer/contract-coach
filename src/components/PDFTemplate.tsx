import React from 'react';

interface PDFTemplateProps {
    content: string;
    title?: string;
    subtitle?: string;
    logoUrl?: string;
}

export const PDFTemplate: React.FC<PDFTemplateProps> = ({
    content,
    title = "Contract Analysis Report",
    subtitle = "EZ Biz Contract Analysis",
    logoUrl = "/Andrometa Brand Kit.svg"
}) => {
    const formatPDFContent = (text: string) => {
        // Parse markdown-like content for PDF formatting
        const lines = text.split('\n');
        const elements: JSX.Element[] = [];
        let key = 0;

        for (let i = 0; i < lines.length; i++) {
            const line = lines[i].trim();

            // Handle headings
            if (line.startsWith('## ')) {
                const headingText = line.substring(3).trim();
                elements.push(
                    <h2 key={key++} className="pdf-heading-2">
                        {headingText}
                    </h2>
                );
            } else if (line.startsWith('### ')) {
                const headingText = line.substring(4).trim();
                elements.push(
                    <h3 key={key++} className="pdf-heading-3">
                        {headingText}
                    </h3>
                );
            } else if (line.startsWith('# ')) {
                const headingText = line.substring(2).trim();
                elements.push(
                    <h1 key={key++} className="pdf-heading-1">
                        {headingText}
                    </h1>
                );
            }
            // Handle lists
            else if (line.startsWith('- ') || line.startsWith('* ')) {
                const listItemText = line.substring(2).trim();
                elements.push(
                    <li key={key++} className="pdf-list-item">
                        {listItemText}
                    </li>
                );
            }
            // Handle paragraphs
            else if (line !== '') {
                let paragraphLines = [line];

                // Group consecutive lines
                while (i + 1 < lines.length && lines[i + 1].trim() !== '' &&
                    !lines[i + 1].trim().startsWith('#')) {
                    i++;
                    paragraphLines.push(lines[i].trim());
                }

                const paragraphText = paragraphLines.join(' ').trim();
                if (paragraphText) {
                    elements.push(
                        <p key={key++} className="pdf-paragraph">
                            {paragraphText}
                        </p>
                    );
                }
            }
        }

        return elements;
    };

    return (
        <div className="pdf-container">
            {/* PDF Header */}
            <div className="pdf-header">
                <div className="pdf-header-content">
                    <div className="pdf-logo-section">
                        <img
                            src={logoUrl}
                            alt="EZ Biz Contract"
                            className="pdf-logo"
                            onError={(e) => {
                                // Fallback if logo fails to load
                                e.currentTarget.style.display = 'none';
                            }}
                        />
                        <div className="pdf-title-section">
                            <h1 className="pdf-main-title">{title}</h1>
                            <p className="pdf-subtitle">{subtitle}</p>
                        </div>
                    </div>
                    <div className="pdf-meta">
                        <p className="pdf-date">Generated: {new Date().toLocaleDateString()}</p>
                        <p className="pdf-url">www.ezbizcontract.com</p>
                    </div>
                </div>
            </div>

            {/* PDF Content */}
            <div className="pdf-content">
                {formatPDFContent(content)}
            </div>

            {/* PDF Footer */}
            <div className="pdf-footer">
                <div className="pdf-footer-content">
                    <p className="pdf-footer-text">
                        This analysis was generated by EZ Biz Contract's AI-powered platform.
                        For questions or support, visit www.ezbizcontract.com
                    </p>
                    <div className="pdf-footer-line"></div>
                    <p className="pdf-page-number">Page 1</p>
                </div>
            </div>
        </div>
    );
};
